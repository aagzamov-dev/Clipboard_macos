public enum ClipboardKind: String, Codable, CaseIterable, Sendable {
    case text, link, code, image, files
    public var isText: Bool { self == .text || self == .link || self == .code }
    public var label: String {
        switch self { case .text: "Text"; case .link: "Link"; case .code: "Code"; case .image: "Image"; case .files: "Files" }
    }
    public var symbol: String {
        switch self { case .text: "text.alignleft"; case .link: "link"; case .code: "chevron.left.forwardslash.chevron.right"; case .image: "photo"; case .files: "doc" }
    }
    public static func classify(_ text: String) -> Self {
        if let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)),
           ["https", "http"].contains(url.scheme?.lowercased() ?? ""), url.host != nil { return .link }
        let prefix = String(text.prefix(2048))
        if ["import ", "func ", "let ", "const ", "function ", "class ", "def ", "SELECT "].contains(where: prefix.hasPrefix) { return .code }
        return .text
    }
}

public enum Limits {
    public static let textBytes = 2 * 1024 * 1024
    public static let rtfBytes = 2 * 1024 * 1024
    public static let imageBytes = 20 * 1024 * 1024
    public static let imagePixels = 64_000_000
    public static let fileCount = 100
    public static let draftBytes = 8 * 1024 * 1024
    public static let archiveBytes: Int64 = 10 * 1024 * 1024 * 1024
    public static let archiveEntries = 200_000
}

public enum CoreError: Error, LocalizedError, Sendable {
    case storage(Int32), invalidData, tooLarge, unsupportedVersion, conflictingIdentity, invalidArchive, cancelled, draftLimit, inaccessibleAttachment
    public var errorDescription: String? {
        switch self {
        case .storage(let code): "History storage is unavailable (code \(code)). Existing data has been preserved."
        case .invalidData: "This clipboard content is invalid or unsupported."
        case .tooLarge: "This item exceeds the supported size limit."
        case .unsupportedVersion: "This file was created by an unsupported version of Clipboard."
        case .conflictingIdentity: "The backup contains an entry that conflicts with existing history. Nothing was imported."
        case .invalidArchive: "The backup is invalid, incomplete, or could not be authenticated. Nothing was imported."
        case .cancelled: "The operation was cancelled."
        case .draftLimit: "Draft memory is full. Save or revert existing drafts before editing more text."
        case .inaccessibleAttachment: "This entry’s managed attachment is missing or unavailable."
        }
    }
}

