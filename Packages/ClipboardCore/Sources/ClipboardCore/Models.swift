public enum DateFilter: String, CaseIterable, Codable, Sendable {
    case all = "All history", today = "Today", yesterday = "Yesterday", week = "7 days", pinned = "Pinned"
    public func range(now: Date, calendar: Calendar = .current) -> Range<Date>? {
        let start = calendar.startOfDay(for: now)
        switch self {
        case .today: return start..<calendar.date(byAdding: .day, value: 1, to: start)!
        case .yesterday: return calendar.date(byAdding: .day, value: -1, to: start)!..<start
        case .week: return calendar.date(byAdding: .day, value: -6, to: start)!..<calendar.date(byAdding: .day, value: 1, to: start)!
        default: return nil
        }
    }
}
