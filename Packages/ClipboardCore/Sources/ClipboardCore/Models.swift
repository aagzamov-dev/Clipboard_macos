public struct ClipboardSnapshot: Sendable {
    public var generation: Int
    public var kind: ClipboardKind
    public var text: String?
    public var representations: [CapturedRepresentation]
    public var sourceBundleID: String?
    public var createdAt: Date
    public init(generation: Int = 0, kind: ClipboardKind, text: String? = nil, representations: [CapturedRepresentation], sourceBundleID: String? = nil, createdAt: Date = Date()) {
        self.generation = generation; self.kind = kind; self.text = text; self.representations = representations; self.sourceBundleID = sourceBundleID; self.createdAt = createdAt
    }
    public static func plainText(_ text: String, date: Date = Date()) -> Self {
        Self(kind: .classify(text), text: text, representations: [.init(type: "public.utf8-plain-text", data: Data(text.utf8))], createdAt: date)
    }
    public var contentHash: String { PayloadRules.hash(kind: kind, text: text, representations: representations) }
}

public enum PayloadRules {
    public static let textType = "public.utf8-plain-text"
    public static let fileType = "public.file-url"
    public static let allowedTypes: Set<String> = [textType, "public.url", "public.rtf", "public.png", "public.tiff", fileType]
    public static let ignoredMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"
    ]
    public static func shouldSkip(types: Set<String>, source: String?, excluded: Set<String>) -> Bool {
        !types.isDisjoint(with: ignoredMarkers) || source.map(excluded.contains) == true
    }
    public static func validate(_ snapshot: ClipboardSnapshot) throws {
        guard snapshot.createdAt.timeIntervalSince1970.isFinite, !snapshot.representations.isEmpty,
              snapshot.representations.count <= 200, snapshot.sourceBundleID?.utf8.count ?? 0 <= 512 else { throw CoreError.invalidData }
        if let text = snapshot.text, text.utf8.count > Limits.textBytes { throw CoreError.tooLarge }
        if snapshot.kind.isText && snapshot.text == nil { throw CoreError.invalidData }
        var keys = Set<String>(), fileCount = 0
        for rep in snapshot.representations {
            guard allowedTypes.contains(rep.type), (0..<100).contains(rep.itemIndex), keys.insert("\(rep.itemIndex):\(rep.type)").inserted else { throw CoreError.invalidData }
            let max = ["public.png", "public.tiff"].contains(rep.type) ? Limits.imageBytes : Limits.textBytes
            guard (rep.type == textType || !rep.data.isEmpty), rep.data.count <= max else { throw CoreError.tooLarge }
            if rep.type == fileType {
                fileCount += 1
                guard rep.data.count <= 16384 else { throw CoreError.tooLarge }
                guard let string = String(data: rep.data, encoding: .utf8), let url = URL(string: string), url.isFileURL else { throw CoreError.invalidData }
            }
        }
        guard fileCount <= Limits.fileCount else { throw CoreError.tooLarge }
        switch snapshot.kind {
        case .text, .link, .code:
            guard snapshot.representations.first(where: { $0.type == textType && $0.itemIndex == 0 })?.data == snapshot.text.map({ Data($0.utf8) }), snapshot.representations.allSatisfy({ $0.itemIndex == 0 }) else { throw CoreError.invalidData }
            guard snapshot.representations.allSatisfy({ [textType, "public.url", "public.rtf"].contains($0.type) }) else { throw CoreError.invalidData }
        case .image:
            guard snapshot.representations.count == 1, ["public.png", "public.tiff"].contains(snapshot.representations[0].type) else { throw CoreError.invalidData }
        case .files:
            guard fileCount == snapshot.representations.count else { throw CoreError.invalidData }
        }
    }
    public static func validateImage(_ snapshot: ClipboardSnapshot) throws {
        guard snapshot.kind == .image else { return }
        guard let rep = snapshot.representations.first, rep.data.count <= Limits.imageBytes,
              let source = CGImageSourceCreateWithData(rep.data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int, let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= Limits.imagePixels / height else { throw CoreError.invalidData }
    }
    public static func hash(kind: ClipboardKind, text: String?, representations: [CapturedRepresentation]) -> String {
        var digest = SHA256()
        func add(_ data: Data) { var length = UInt64(data.count).bigEndian; withUnsafeBytes(of: &length) { digest.update(data: Data($0)) }; digest.update(data: data) }
        add(Data(kind.rawValue.utf8)); add(Data((text ?? "").utf8))
        for rep in representations.sorted(by: { ($0.itemIndex, $0.type) < ($1.itemIndex, $1.type) }) {
            add(Data(String(rep.itemIndex).utf8)); add(Data(rep.type.utf8)); add(rep.data)
        }
        return digest.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

