public struct SelectionState: Sendable {
    public private(set) var ids = Set<UUID>()
    public private(set) var anchor: UUID?
    public init() {}
    public mutating func select(_ id: UUID, ordered: [UUID], command: Bool = false, shift: Bool = false) {
        if shift, let anchor, let a = ordered.firstIndex(of: anchor), let b = ordered.firstIndex(of: id) {
            let range = Set(ordered[min(a,b)...max(a,b)])
            ids = command ? ids.union(range) : range
        } else if command { if !ids.insert(id).inserted { ids.remove(id) }; anchor = id }
        else { ids = [id]; anchor = id }
    }
    public mutating func replace(_ ids: Set<UUID>) { self.ids = ids; anchor = nil }
    public mutating func retain(_ visible: Set<UUID>) { ids.formIntersection(visible) }
}
public struct DraftStore: Sendable {
    private var drafts: [UUID: String] = [:]
    public init() {}
    public var ids: Set<UUID> { Set(drafts.keys) }
    public var isEmpty: Bool { drafts.isEmpty }
    public var byteCount: Int { drafts.values.reduce(0) { $0 + $1.utf8.count } }
    public func text(for id: UUID) -> String? { drafts[id] }
    public mutating func set(_ text: String, for id: UUID, original: String) throws {
        guard text.utf8.count <= Limits.textBytes else { throw CoreError.tooLarge }
        if text == original { drafts[id] = nil; return }
        guard drafts[id] != nil || drafts.count < 500 else { throw CoreError.draftLimit }
        let used = drafts.filter { $0.key != id }.reduce(0) { $0 + $1.value.utf8.count }
        guard used + text.utf8.count <= Limits.draftBytes else { throw CoreError.draftLimit }
        drafts[id] = text
    }
    public mutating func remove(_ id: UUID) { drafts[id] = nil }
    public mutating func removeAll() { drafts.removeAll() }
}

public struct ConsecutiveDeduplicator: Sendable {
    private var lastCommittedHash: String?
    public init() {}
    public func accepts(_ hash: String) -> Bool { hash != lastCommittedHash }
    public mutating func committed(_ hash: String) { lastCommittedHash = hash }
    public mutating func reset() { lastCommittedHash = nil }
}

public struct CombinedCopyDraft: Sendable {
    public let ids: [UUID]
    public let original: String
    public private(set) var text: String
    public var hasChanges: Bool { text != original }
    public var editedByteCount: Int { hasChanges ? text.utf8.count : 0 }
    public init(ids: [UUID], text: String) { self.ids = ids; original = text; self.text = text }
    public mutating func set(_ text: String, otherDraftBytes: Int) throws {
        guard text.utf8.count <= Limits.textBytes else { throw CoreError.tooLarge }
        guard otherDraftBytes + (text == original ? 0 : text.utf8.count) <= Limits.draftBytes else { throw CoreError.draftLimit }
        self.text = text
    }
    public mutating func revert() { text = original }
}
